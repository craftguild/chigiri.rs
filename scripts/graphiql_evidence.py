"""Retain actual esbuild contributions and exact embedded assets for the SBOM."""

import json
from pathlib import Path
import shutil
import tempfile

from implementation_rule_io import components, require


def export(work, metadata, repository):
    parent = repository / ".craftguild"
    parent.mkdir(exist_ok=True)
    require(parent.is_dir() and not parent.is_symlink())
    destination = parent / "graphiql-evidence"
    require(not destination.is_symlink())
    selected = set()
    for output in metadata["outputs"].values():
        for name, contribution in output["inputs"].items():
            if contribution["bytesInOutput"] > 0:
                selected.add(name)
    # A font copied by esbuild has no executable byte contribution. Retain its
    # actual source and identify it separately from the JavaScript modules.
    selected.update(name for name in metadata["inputs"] if name.endswith(".ttf"))
    for name in list(selected):
        components(name)
        source = work / name
        require(source.is_file() and not source.is_symlink())
        require(source.stat().st_size == metadata["inputs"][name]["bytes"])
        package = source.parent
        while package != work:
            manifest = package / "package.json"
            if manifest.is_file() and json.loads(manifest.read_text()).get("name"):
                selected.add(manifest.relative_to(work).as_posix())
                break
            package = package.parent
    with tempfile.TemporaryDirectory(prefix="graphiql-proof-", dir=parent) as temporary:
        stage = Path(temporary) / "proof"
        stage.mkdir()
        for name in sorted(selected | {"package.json", "package-lock.json", "meta.json"}):
            components(name)
            target = stage / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(work / name, target)
        shutil.copytree(work / "assets", stage / "assets")
        supplemental = [{
            "name": "FIGlet Small Slant banner", "version": "2.1-1996-layout",
            "type": "file", "reference": "urn:chigiri:asset:small-slant-banner",
            "license": "BSD-3-Clause",
            "files": ["crates/cli/assets/version-banner.txt", "crates/cli/assets/FIGlet-LICENSE",
                      "crates/cli/assets/NOTICE.md"],
            "evidence": "The shipped ASCII artwork is generated by the immutable standards tool from Glenn Chappell's Small Slant font with Paul Burton's 1996 layout update. The font and FIGlet renderer are build-tool inputs, not CLI runtime libraries; attribution and license are retained beside the artwork.",
        }]
        all_assets = {path.relative_to(stage).as_posix() for path in (stage / "assets").rglob("*") if path.is_file()}
        unlisted = all_assets - set(metadata["outputs"])
        if unlisted:
            supplemental.append({
                "name": "graphiql-license-notices", "version": "1",
                "type": "file", "reference": "urn:chigiri:graphiql:notices",
                "files": [f".craftguild/graphiql-evidence/{name}" for name in sorted(unlisted)],
                "evidence": "Exact non-module notice files produced by esbuild and the pinned license inventory; each byte also matches the embedded asset inventory.",
            })
        fonts = sorted(name for name in all_assets if name.endswith(".ttf"))
        if fonts:
            sources = sorted(name for name in selected if name.endswith(".ttf"))
            require(len(fonts) == len(sources) == 1)
            require((stage / fonts[0]).read_bytes() == (stage / sources[0]).read_bytes())
            lock = json.loads((stage / "package-lock.json").read_text())
            supplemental.append({
                "name": "monaco-editor-codicon-font",
                "version": lock["packages"]["node_modules/monaco-editor"]["version"],
                "type": "file", "reference": "urn:chigiri:graphiql:codicon-font",
                "files": [f".craftguild/graphiql-evidence/{name}" for name in fonts + sources],
                "evidence": "The esbuild font output equals the locked monaco-editor input byte-for-byte. Package licenses and third-party notices remain in the shipped notice file; a distinct font license is not inferred from its filename.",
            })
        require(supplemental)
        (stage / "supplemental.json").write_text(json.dumps(supplemental, indent=2) + "\n")
        if destination.exists():
            shutil.rmtree(destination)
        stage.rename(destination)


if __name__ == "__main__":
    import subprocess
    import sys
    root = Path(__file__).resolve().parent.parent
    subprocess.run([sys.executable, str(root / "scripts/graphiql_build.py"), "--check", "--evidence"],
                   cwd=root, check=True, timeout=600)
