"""SG-LAYOUT-02: retain closed generated ownership independently of Code measurement."""

import copy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import implementation_rule_io as safe_io
from generated_inventory import MARKER, owned_rust

REPOSITORY = Path(__file__).resolve().parent.parent


class Ownership(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="chigiri-owned-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        scripts = self.root / "scripts"
        scripts.mkdir()
        for name in (
            "check-implementation-rules.sh",
            "check_host_boundary.py",
            "check_repository_language.py",
            "python-with-toml.sh",
            "implementation_rules.py",
            "implementation_rule_io.py",
            "generated_inventory.py",
            "graphiql_inventory.py",
        ):
            shutil.copyfile(REPOSITORY / "scripts" / name, scripts / name)
        (scripts / "generated-manifests.json").write_text('["chigiri-books.toml"]\n')
        (self.root / "chigiri-books.toml").write_text('schema_version="chigiri/config-v2"\n[generation]\noutput="generated/contract"\n')
        self.output = self.root / "generated/contract"
        shutil.copytree(REPOSITORY / "generated/books", self.output)
        self.record = json.loads((self.output / MARKER).read_bytes())

    def run_checker(self, expected):
        result = subprocess.run(["bash", str(self.root / "scripts/python-with-toml.sh"), str(self.root / "scripts/implementation_rules.py")], capture_output=True, text=True, timeout=15)
        self.assertEqual(result.returncode, expected, result.stdout + result.stderr)
        return result.stdout + result.stderr

    def store(self):
        (self.output / MARKER).write_text(json.dumps(self.record) + "\n")

    def amend(self, path, data):
        (self.output / path).write_bytes(data)
        for record in self.record["files"]:
            if record["path"] == path:
                record.update(bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
                break
        else:
            self.fail("test must amend a file in the existing inventory")
        self.store()

    def test_generated_401_lines_are_exempt_and_counted(self):
        # Extending an owned generated fixture must not make it count as handwritten code.
        data = (self.output / "src/lib.rs").read_bytes() + "// Generated ownership line-count fixture.\n".encode() * 450
        self.amend("src/lib.rs", data)
        result = self.run_checker(0)
        count = sum(record["path"].endswith(".rs") for record in self.record["files"])
        self.assertIn(f"{count} generated files excluded", result)

    def test_handwritten_renderer_consumer_test_and_scaffold_are_not_exempt(self):
        for name in ("crates/codegen/src/render/fixture.rs", "consumer/src/generated.rs", "tests/generated/fixture.rs", "application/scaffold.rs"):
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("// This file was generated by Chigiri.\n" * 401)
        self.run_checker(0)
        owned = owned_rust(self.root)
        for name in ("crates/codegen/src/render/fixture.rs", "consumer/src/generated.rs", "tests/generated/fixture.rs", "application/scaffold.rs"):
            self.assertNotIn(name, owned)

    def test_arbitrary_marker_outside_registry_does_not_exempt(self):
        shutil.copytree(self.output, self.root / "unregistered/generated")
        (self.root / "unregistered/generated/src/lib.rs").write_text("// Fake generated artifact.\n" * 401)
        self.run_checker(0)
        self.assertNotIn("unregistered/generated/src/lib.rs", owned_rust(self.root))

    def test_short_unknown_file_and_empty_directory_are_rejected(self):
        for name in ("manual.rs", "src/manual.rs", "Cargo.lock", "empty"):
            path = self.output / name
            path.mkdir() if name == "empty" else path.write_text("// Handwriting.\n")
            self.assertIn("Generated Rust/asset ownership check failed", self.run_checker(1))
            path.rmdir() if path.is_dir() else path.unlink()

    def test_missing_marker_and_file_and_changed_bytes_are_rejected(self):
        for name in (MARKER, "src/lib.rs"):
            path = self.output / name
            data = path.read_bytes()
            path.unlink()
            self.run_checker(1)
            path.write_bytes(data)
        with (self.output / "src/lib.rs").open("a") as output:
            output.write("// Malformed ownership marker fixture.\n")
        self.run_checker(1)

    def test_closed_marker_unknown_keys_and_invalid_fields_are_rejected(self):
        original = copy.deepcopy(self.record)
        for key in (None, "package", "generator", "runtime", "provenance"):
            self.record = copy.deepcopy(original)
            target = self.record if key is None else self.record[key]
            target["unknown"] = True
            self.store()
            self.run_checker(1)
        for locate in (lambda value: value["generator"]["build"], lambda value: value["files"][0], lambda value: value["provenance"]["sources"][0]):
            self.record = copy.deepcopy(original)
            locate(self.record)["unknown"] = True
            self.store()
            self.run_checker(1)
        self.record = copy.deepcopy(original)
        self.record["generator"]["dirty"] = None
        self.store()
        self.run_checker(1)
        self.record = copy.deepcopy(original)
        self.record["files"][0]["bytes"] = True
        self.store()
        self.run_checker(1)

    def test_duplicate_json_and_oversize_marker_are_rejected(self):
        original = (self.output / MARKER).read_text()
        mutated = original.replace('"abi": 8', '"abi": 8, "abi": 8')
        self.assertNotEqual(original, mutated)
        (self.output / MARKER).write_text(mutated)
        self.run_checker(1)
        (self.output / MARKER).write_bytes(b" " * (1024 * 1024 + 1))
        self.run_checker(1)

    def test_record_escape_duplicate_case_collision_and_utf8_are_rejected(self):
        original = copy.deepcopy(self.record)
        for name in ("../outside.rs", "/outside.rs", "src/../outside.rs", "src/lib.rs", "src/LIB.rs"):
            self.record = copy.deepcopy(original)
            self.record["files"].append(dict(path=name, bytes=0, sha256="0" * 64))
            self.record["files"].sort(key=lambda item: item["path"])
            self.store()
            self.run_checker(1)
        self.record = original
        self.amend("src/lib.rs", b"\xff")
        self.run_checker(1)

    def test_final_parent_manifest_symlink_and_fifo_are_rejected(self):
        for path in (self.output / MARKER, self.output / "src/lib.rs", self.output / "src", self.root / "chigiri-books.toml"):
            retained = path.with_name(path.name + ".retained")
            path.rename(retained)
            path.symlink_to(retained.name)
            self.run_checker(1)
            path.unlink()
            retained.rename(path)
        path = self.output / "src/lib.rs"
        path.unlink()
        os.mkfifo(path)
        self.run_checker(1)

    def test_registry_missing_unknown_manifest_and_overlapping_roots_fail(self):
        registry = self.root / "scripts/generated-manifests.json"
        for source in ('["missing.toml"]', '["chigiri-books.toml", "chigiri-books.toml"]', '{}'):
            registry.write_text(source)
            self.run_checker(1)
        registry.unlink()
        self.run_checker(1)
        for output in ("generated/contract", "generated/contract/child", "generated/CONTRACT"):
            (self.root / "second.toml").write_text(f'schema_version="chigiri/config-v2"\n[generation]\noutput="{output}"\n')
            registry.write_text('["chigiri-books.toml", "second.toml"]')
            self.run_checker(1)

    def test_actual_byte_limit_is_rejected_without_reading_a_sparse_file(self):
        with (self.output / "src/lib.rs").open("wb") as output:
            output.truncate(64 * 1024 * 1024 + 1)
        self.run_checker(1)

    def test_directory_swap_and_entry_budget_fail_closed(self):
        root = self.root / "race"
        root.mkdir()
        with self.assertRaises(safe_io.Invalid):
            with safe_io.directory(root):
                root.rename(self.root / "retained")
                root.mkdir()
        with patch.object(safe_io, "MAX_ENTRIES", 1):
            with self.assertRaises(safe_io.Invalid):
                safe_io.visit_tree(self.output, lambda _name, _data: None)


if __name__ == "__main__":
    unittest.main()
