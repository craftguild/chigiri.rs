//! Publish limit values directly from the executable constants.

use super::{
    ReferenceError,
    api_types::{LimitDoc, LimitUnit},
    budget::Budget,
};
use crate::{api, luau, runtime, schema, store, value};

pub(super) fn append(rows: &mut Vec<LimitDoc>, budget: &mut Budget) -> Result<(), ReferenceError> {
    use LimitUnit::*;
    for (id, value, unit, scope, description) in [
        (
            "config.bytes",
            crate::limits::CONFIG_BYTES,
            Bytes,
            "config",
            "Maximum bytes in a portable TOML configuration",
        ),
        (
            "seed.bytes",
            crate::limits::SEED_BYTES,
            Bytes,
            "seed",
            "Maximum bytes in one seed JSON line",
        ),
        (
            "value.id_bytes",
            crate::limits::ID_BYTES,
            Bytes,
            "id",
            "Maximum UTF-8 bytes in a non-empty model key or relation ID",
        ),
        (
            "schema.sources",
            crate::limits::SDL_SOURCES,
            Items,
            "schema",
            "Maximum number of public and storage SDL sources",
        ),
        (
            "schema.types",
            crate::limits::SDL_TYPES,
            Items,
            "schema",
            "Maximum schema types, excluding built-in vocabulary",
        ),
        (
            "schema.members",
            crate::limits::SDL_MEMBERS,
            Items,
            "schema",
            "Maximum total fields, arguments, and input members",
        ),
        (
            "schema.models",
            crate::limits::MODELS,
            Items,
            "schema",
            "Number of models",
        ),
        (
            "schema.scripts",
            crate::limits::SCRIPTS,
            Items,
            "schema",
            "Maximum number of resolver and hook script coordinates",
        ),
        (
            "worker.queued_jobs",
            crate::limits::QUEUED_JOBS,
            Items,
            "worker",
            "Maximum queued worker jobs",
        ),
        (
            "operation.time",
            crate::limits::OPERATION_TIME.as_millis() as usize,
            Milliseconds,
            "operation",
            "Maximum duration of one complete HTTP operation",
        ),
        (
            "shutdown.time",
            crate::limits::SHUTDOWN_TIME.as_millis() as usize,
            Milliseconds,
            "shutdown",
            "Maximum worker and output-pager shutdown wait",
        ),
        (
            "query.predicate_depth",
            api::query::PREDICATE_DEPTH,
            Depth,
            "predicate",
            "Maximum predicate depth, counting the root as one level",
        ),
        (
            "query.predicate_nodes",
            api::query::PREDICATE_NODES,
            Nodes,
            "predicate",
            "Maximum predicate nodes, including empty groups",
        ),
        (
            "query.in_items",
            api::query::IN_ITEMS,
            Items,
            "leaf",
            "Maximum values in one `in` operand list",
        ),
        (
            "query.operand_bytes",
            api::query::OPERAND_BYTES,
            Bytes,
            "operand",
            "Maximum UTF-8 bytes in a string comparison operand",
        ),
        (
            "query.sort_keys",
            api::query::SORT_KEYS,
            Items,
            "find",
            "Maximum sort keys; duplicate fields are rejected",
        ),
        (
            "query.offset",
            api::FIND_OFFSET.maximum,
            Items,
            "find",
            "Maximum accepted query offset",
        ),
        (
            "query.limit",
            api::FIND_LIMIT.maximum,
            Items,
            "find",
            "Maximum accepted query limit; result values have separate budgets",
        ),
        (
            "host.calls",
            api::HOST_CALL_LIMIT,
            Calls,
            "scope",
            "Maximum host calls shared by model operations and JSON validation",
        ),
        (
            "host.work",
            api::WORK_LIMIT,
            Work,
            "scope",
            "Work budget shared by scans, sorts, and string comparisons",
        ),
        (
            "value.bytes",
            value::MAX_BYTES,
            Bytes,
            "scope",
            "Byte budget shared while converting one value graph",
        ),
        (
            "value.depth",
            value::MAX_DEPTH,
            Depth,
            "value",
            "Maximum nested value depth",
        ),
        (
            "value.items",
            value::MAX_ITEMS,
            Items,
            "list_or_json_array",
            "Maximum items in one list or JSON array; object fields are counted separately",
        ),
        (
            "value.nodes",
            value::MAX_NODES,
            Nodes,
            "scope",
            "Node budget shared by one converted value graph",
        ),
        (
            "value.string_bytes",
            value::MAX_STRING_BYTES,
            Bytes,
            "string",
            "Maximum UTF-8 bytes in one string value",
        ),
        (
            "store.bytes",
            value::MAX_BYTES,
            Bytes,
            "store",
            "Logical byte budget shared by all stored model records",
        ),
        (
            "store.nodes",
            value::MAX_NODES,
            Nodes,
            "store",
            "Node budget shared by all stored model records",
        ),
        (
            "store.model_records",
            store::MODEL_RECORDS,
            Items,
            "model",
            "Maximum records stored for one model",
        ),
        (
            "store.total_records",
            store::TOTAL_RECORDS,
            Items,
            "store",
            "Maximum records stored across all models",
        ),
        (
            "schema.bytes",
            schema::MAX_SDL_BYTES,
            Bytes,
            "schema",
            "Maximum aggregate bytes of user-owned SDL",
        ),
        (
            "luau.body_bytes",
            luau::MAX_BODY,
            Bytes,
            "resolver",
            "Maximum bytes in one user-owned Luau body",
        ),
        (
            "luau.wrapper_bytes",
            luau::MAX_WRAPPER,
            Bytes,
            "resolver",
            "Maximum bytes in one generated type-check wrapper",
        ),
        (
            "luau.generated_bytes",
            luau::MAX_GENERATED,
            Bytes,
            "schema",
            "Maximum aggregate bytes of generated Luau declarations",
        ),
        (
            "vm.memory_bytes",
            value::MAX_BYTES,
            Bytes,
            "vm",
            "VM allocator limit, not process RSS limit.",
        ),
        (
            "vm.time",
            runtime::VM_TIME.as_millis() as usize,
            Milliseconds,
            "resolver",
            "Maximum resolver time, including VM waits and host processing",
        ),
        (
            "vm.pcall_reentry",
            crate::protected_call::REENTRY_LIMIT,
            Depth,
            "vm",
            "Maximum nested `pcall` re-entry depth",
        ),
        (
            "reference.document_bytes",
            super::MAX_REFERENCE_BYTES,
            Bytes,
            "document",
            "Maximum JSON bytes in one reference document",
        ),
        (
            "reference.output_bytes",
            super::MAX_REFERENCE_BYTES,
            Bytes,
            "output",
            "Maximum bytes in one rendered text or JSON reference output",
        ),
    ] {
        budget.push(
            rows,
            LimitDoc {
                id: id.into(),
                value,
                unit,
                shared_scope: scope.into(),
                description: description.into(),
            },
        )?;
    }
    super::constraint_limits::append(rows, budget)?;
    super::request_limits::append(rows, budget)
}
