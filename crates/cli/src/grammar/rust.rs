//! Rust namespace grammar and typed actions.

use std::path::PathBuf;

use chigiri_codegen::DiagnosticFormat;
use clap::{Arg, ArgAction, ArgMatches, Command};

use super::{closed, flag};

#[derive(Clone, Copy)]
pub enum ContractCommand {
    Codegen,
    Update,
    Check,
    Doctor,
}

pub enum RustAction {
    Init {
        manifest: PathBuf,
        format: DiagnosticFormat,
    },
    Contract {
        command: ContractCommand,
        manifest: PathBuf,
        format: DiagnosticFormat,
        deny_warnings: bool,
    },
}

pub fn command() -> Command {
    let commands = [
        Command::new("init").about("Create only a new editable Rust manifest"),
        Command::new("codegen").about("Generate a standalone contract crate for the first time"),
        Command::new("update").about("Replace an existing verified generated crate"),
        Command::new("check").about("Compare every generated byte and ownership record"),
        Command::new("doctor").about("Check generated output and validate the real consumer"),
    ];
    let names = commands
        .iter()
        .map(|command| command.get_name().to_owned())
        .collect::<Vec<_>>();
    closed(
        Command::new("rust")
            .about("Generate and validate the chigiri.rs Rust contract crate")
            .arg(
                Arg::new("manifest")
                    .long("manifest")
                    .value_name("PATH")
                    .value_parser(clap::value_parser!(PathBuf))
                    .default_value("chigiri.toml")
                    .global(true),
            )
            .arg(
                Arg::new("format")
                    .long("format")
                    .value_parser(["human", "json"])
                    .default_value("human")
                    .global(true),
            )
            .arg(
                flag("deny-warnings", "Treat warnings as errors")
                    .global(true)
                    .action(ArgAction::SetTrue),
            )
            .subcommands(commands.into_iter().map(closed))
            .subcommand(closed(
                Command::new("help")
                    .about("Print Rust command help")
                    .arg(Arg::new("command").value_parser(names)),
            )),
    )
}

pub fn parse(matches: &ArgMatches) -> Result<RustAction, String> {
    let (name, args) = matches
        .subcommand()
        .ok_or_else(|| "usage: Rust command required; see --help".to_owned())?;
    let manifest = args
        .get_one::<PathBuf>("manifest")
        .expect("clap supplies the manifest")
        .clone();
    let format = format(args);
    let deny_warnings = args.get_flag("deny-warnings");
    let command = match name {
        "codegen" => Some(ContractCommand::Codegen),
        "update" => Some(ContractCommand::Update),
        "check" => Some(ContractCommand::Check),
        "doctor" => Some(ContractCommand::Doctor),
        _ => None,
    };
    if let Some(command) = command {
        return Ok(RustAction::Contract {
            command,
            manifest,
            format,
            deny_warnings,
        });
    }
    match name {
        "init" => Ok(RustAction::Init { manifest, format }),
        _ => Err("usage: invalid Rust command; see --help".into()),
    }
}

pub fn format(matches: &ArgMatches) -> DiagnosticFormat {
    let mut current = matches;
    while let Some((_, child)) = current.subcommand() {
        current = child;
    }
    if current.get_one::<String>("format").map(String::as_str) == Some("json") {
        DiagnosticFormat::Json
    } else {
        DiagnosticFormat::Human
    }
}
