//! Reuse recorded generator inputs and compare the captured tree with current output.

#[cfg(test)]
mod difference_tests;
#[cfg(test)]
pub(super) mod fixture;
#[cfg(test)]
mod tests;

use chigiri_core::GeneratorInfo;

use crate::filesystem::{CapturedTree, TreeLimits};
use crate::{CodegenError, ResolvedManifest};

use super::differences::Differences;
use super::{GENERATED_MARKER_FILE, marker, render_recorded};

/// The exact check compares the two generators.
#[derive(Debug)]
pub struct ContractCheck {
    pub(crate) output: CapturedTree,
    /// The information was recorded on the captured product.
    pub recorded: GeneratorInfo,
    /// Verifies recorded codegen build information.
    pub current: GeneratorInfo,
}

impl ContractCheck {
    /// Return whether the recorded generator differs from the current generator.
    ///
    /// Callers may report this as an informational notice; it is not affected by
    /// `deny-warnings`.
    pub fn generator_differs(&self) -> bool {
        self.recorded != self.current
    }
}

/// Compares all generated bytes without modifying the manifest or output tree and
/// without invoking Cargo or the network.
pub fn check_contract(manifest: &ResolvedManifest) -> Result<ContractCheck, CodegenError> {
    crate::cancellation::check()?;
    let tree = capture_output(manifest).map_err(|error| repair(manifest, error))?;
    let recorded = marker::read(&tree).map_err(|error| repair(manifest, error))?;
    let expected = render_recorded(manifest, &recorded)?;
    if let Some(error) = Differences::compare(&expected.files, &tree.files).error(
        "SF4009",
        "The generated crate differs byte-for-byte from the manifest, SDL, or renderer output.",
    ) {
        return Err(repair(manifest, error));
    }
    manifest.verify_paths()?;
    marker::verify_inputs(manifest, &tree)?;
    Ok(ContractCheck {
        output: tree,
        recorded,
        current: crate::generator_info().clone(),
    })
}

impl ContractCheck {
    /// Re-render a checked contract with its validated recorded producer identity.
    ///
    /// This supports isolated byte-for-byte reproduction without restamping an
    /// owned crate. Inputs and the captured output must still be unchanged.
    pub fn render(
        &self,
        manifest: &ResolvedManifest,
    ) -> Result<super::RenderedContract, CodegenError> {
        self.verify(manifest)?;
        let rendered = render_recorded(manifest, &self.recorded)?;
        if let Some(error) = Differences::compare(&rendered.files, &self.output.files).error(
            "SF4009",
            "The checked contract changed before isolated reproduction.",
        ) {
            return Err(error);
        }
        Ok(rendered)
    }

    pub(crate) fn verify(&self, manifest: &ResolvedManifest) -> Result<(), CodegenError> {
        let current = capture_output(manifest)?;
        if current != self.output {
            return Err(CodegenError::new(
                "SF4009",
                "The generated crate changed during doctor validation.",
            ));
        }
        marker::verify_inputs(manifest, &self.output)
    }
}

pub(crate) fn capture_output(manifest: &ResolvedManifest) -> Result<CapturedTree, CodegenError> {
    manifest.verify_paths()?;
    let root = manifest
        .root
        .relative(manifest.manifest().output())
        .map_err(capture_error)?;
    let tree = root
        .capture_limited(
            TreeLimits {
                depth: 64,
                entries: 65_536,
                files: 65_536,
                file_bytes: 64 * 1024 * 1024,
                total_bytes: 64 * 1024 * 1024,
            },
            |path| {
                Some(if path == GENERATED_MARKER_FILE {
                    1024 * 1024
                } else {
                    64 * 1024 * 1024
                })
            },
        )
        .map_err(capture_error)?;
    Ok(tree)
}

fn capture_error(error: crate::filesystem::FsError) -> CodegenError {
    use crate::filesystem::FsError;
    let code = match error {
        FsError::Unsupported => "SF4022",
        FsError::Io => "SF4008",
        FsError::Cancelled => "SF4026",
        _ => "SF4020",
    };
    CodegenError::new(code, format!("generated crate I/O: {error}"))
}

fn repair(manifest: &ResolvedManifest, error: CodegenError) -> CodegenError {
    let Some(primary) = error.report().diagnostics().first() else {
        return error;
    };
    let action = match primary.code() {
        "SF4009" => "update",
        "SF4020" | "SF4021" => "codegen",
        _ => return error,
    };
    let label = manifest.manifest_label();
    let command = if label == "chigiri.toml" {
        format!("chigiri rust {action}")
    } else {
        format!(
            "chigiri rust --manifest '{}' {action}",
            label.replace('\'', "'\\''")
        )
    };
    let help = if action == "codegen" {
        format!(
            "Move the existing generated tree to a different name, then run `{command}` from the manifest directory."
        )
    } else {
        format!("Run `{command}` from the manifest directory.")
    };
    let mut diagnostics = error.report().diagnostics().to_vec();
    diagnostics[0] = diagnostics[0].clone().with_help(help);
    CodegenError::from_report(crate::DiagnosticReport::new(
        diagnostics,
        error.report().truncated(),
    ))
}
