//! Stamps generated Rust without altering the core model or colliding with SDL names.

use chigiri_core::GeneratorInfo;

use crate::{CodegenError, formatter::format_source, writer::rust_string_literal};

const GENERATED_HEADER: &str = "// This file was generated by Chigiri. Do not edit it manually.";
const GENERATED_OBSERVATION: &str =
    "// Information captured at generation time; never rediscovered at runtime.";

pub(super) fn render(info: &GeneratorInfo) -> Result<String, CodegenError> {
    info.validate().map_err(|_| {
        CodegenError::new(
            "SF4021",
            "Generator information failed integrity validation.",
        )
    })?;
    let text = |value: &str| {
        format!(
            "::std::borrow::Cow::Borrowed({})",
            rust_string_literal(value)
        )
    };
    let commit = info.git_commit.as_ref().map_or_else(
        || "::std::option::Option::None".to_owned(),
        |value| format!("::std::option::Option::Some({})", text(value)),
    );
    let dirty = info.dirty.map_or_else(
        || "::std::option::Option::None".to_owned(),
        |value| format!("::std::option::Option::Some({value})"),
    );
    let source = format!(
        "{GENERATED_HEADER}\n\
         {GENERATED_OBSERVATION}\n\
         pub(super) static INFO: ::chigiri::core::GeneratorInfo = ::chigiri::core::GeneratorInfo {{\n\
         schema_version: {},\nversion: {},\nrevision: {},\ngit_commit: {commit},\ndirty: {dirty},\n\
         build: ::chigiri::core::GeneratorBuild {{ rustc: {}, host: {}, target: {}, profile: {} }},\n}};\n",
        text(&info.schema_version),
        text(&info.version),
        text(&info.revision),
        text(&info.build.rustc),
        text(&info.build.host),
        text(&info.build.target),
        text(&info.build.profile),
    );
    format_source("generator information", &source)
}

pub(super) const ROOT: &str = r#"
#[path = "__chigiri/generator_info.rs"]
mod __generator;

/// Build information for the generator that created this contract crate.
pub fn generator() -> &'static ::chigiri::core::GeneratorInfo {
    &__generator::INFO
}
"#;
