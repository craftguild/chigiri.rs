//! Render a Cargo manifest with runtime paths rebased to the generated crate.

#[cfg(test)]
mod license_tests;
#[cfg(test)]
mod tests;

use crate::filesystem::Directory;
use crate::{CodegenError, ResolvedManifest, RuntimeSource};

pub(super) fn render(manifest: &ResolvedManifest) -> Result<String, CodegenError> {
    let output = crate::filesystem::PortableRelativePath::new(manifest.manifest().output())
        .map_err(path_error)?;
    render_from(manifest, &output)
}

pub(super) fn render_at(
    manifest: &ResolvedManifest,
    directory: &Directory,
) -> Result<String, CodegenError> {
    render_with(manifest, |runtime| directory.reference_to(runtime))
}

fn render_from(
    manifest: &ResolvedManifest,
    directory: &crate::filesystem::PortableRelativePath,
) -> Result<String, CodegenError> {
    render_with(manifest, |runtime| {
        manifest.root.reference_from_descendant(directory, runtime)
    })
}

fn render_with(
    manifest: &ResolvedManifest,
    relative: impl FnOnce(&Directory) -> Result<String, crate::filesystem::FsError>,
) -> Result<String, CodegenError> {
    let config = manifest.manifest();
    let runtime = match config.runtime() {
        RuntimeSource::Git {
            url,
            revision,
            version,
        } => {
            let version = version
                .as_ref()
                .map(|version| format!(", version = {}", quote(&format!("={version}"))))
                .unwrap_or_default();
            format!("git = {}, rev = {}{version}", quote(url), quote(revision))
        }
        RuntimeSource::Path { root } => {
            let runtime = manifest
                .root
                .resolve_directory(std::path::Path::new(root))
                .and_then(|root| root.relative("crates/facade"))
                .map_err(path_error)?;
            let path = relative(&runtime).map_err(path_error)?;
            runtime.verify().map_err(|error| {
                CodegenError::new("SF4023", format!("runtime Path I/O: {error}"))
            })?;
            format!("path = {}", quote(&path))
        }
    };
    let package = config.package();
    let license = package
        .license
        .as_ref()
        .map(|value| format!("license = {}\n", quote(value)))
        .unwrap_or_default();
    Ok(format!(
        "# This file was generated by Chigiri. Do not edit it manually.\n\
         [package]\nname = {}\nversion = {}\nedition = {}\n{license}rust-version = \"1.95\"\npublish = false\n\n\
         [workspace]\n\n[dependencies]\nchigiri = {{ package = \"chigiri\", {runtime} }}\n",
        quote(&package.name),
        quote(&package.version),
        quote(&package.edition),
    ))
}

fn quote(value: &str) -> String {
    toml_edit::Value::from(value).to_string()
}

fn path_error(error: crate::filesystem::FsError) -> CodegenError {
    CodegenError::new("SF4023", format!("runtime Path I/O: {error}"))
}
